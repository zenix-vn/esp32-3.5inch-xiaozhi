"""Resizes the Zenix logo (tools/assets/zenix_logo.png) for the About page and writes it as an LVGL image.

    python tools/gen_logo.py [preview.png]

Output: firmware/src/zenix_logo.c + zenix_logo.h (LV_IMG_CF_TRUE_COLOR_ALPHA, fits in 72x64).
"""
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_dragons  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'assets', 'zenix_logo.png')
OUT_C = os.path.join(ROOT, 'firmware', 'src', 'zenix_logo.c')
OUT_H = os.path.join(ROOT, 'firmware', 'src', 'zenix_logo.h')
BOX = (72, 64)


def main():
    logo = Image.open(SRC).convert('RGBA')
    logo = logo.crop(logo.getchannel('A').getbbox())
    k = min(BOX[0] / logo.size[0], BOX[1] / logo.size[1])
    logo = logo.resize((max(1, round(logo.size[0] * k)), max(1, round(logo.size[1] * k))), Image.LANCZOS)
    if len(sys.argv) > 1:
        bg = Image.new('RGBA', (logo.size[0] * 4 + 40, logo.size[1] * 4 + 40), (21, 27, 51, 255))
        bg.alpha_composite(logo.resize((logo.size[0] * 4, logo.size[1] * 4), Image.NEAREST), (20, 20))
        bg.save(sys.argv[1])
    w, h, data = gen_dragons.to_lvgl(logo)
    with open(OUT_C, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/gen_logo.py - do not edit.\n#include "zenix_logo.h"\n\nstatic const uint8_t zenix_logo_map[] = {\n')
        for i in range(0, len(data), 24):
            f.write('  ' + ','.join(f'0x{x:02x}' for x in data[i:i + 24]) + ',\n')
        f.write('};\n')
        f.write(f'const lv_img_dsc_t zenix_logo = {{\n  .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = {w}, .h = {h}}},\n'
                f'  .data_size = {len(data)},\n  .data = zenix_logo_map,\n}};\n')
    with open(OUT_H, 'w', encoding='utf-8', newline='\n') as f:
        f.write('#pragma once\n// Generated by tools/gen_logo.py - do not edit.\n#include <lvgl.h>\n\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern const lv_img_dsc_t zenix_logo;\n#ifdef __cplusplus\n}\n#endif\n')
    print(f'logo {w}x{h}, {len(data)} bytes')


if __name__ == '__main__':
    main()
